const { APP, ok, launch, run, SP, BACKUP } = require('../helpers.cjs');
run(async () => {
  const browser = await launch();
  const page = await (await browser.newContext({ viewport: { width: 430, height: 900 }, serviceWorkers: 'block' })).newPage();
  const errors = [];
  page.on('pageerror', (e) => errors.push('pageerror: ' + e.message));
  await page.goto(APP, { waitUntil: 'networkidle' });
  await page.click('text=Open Import & Export');
  await page.setInputFiles('#ie-file', BACKUP); await page.waitForTimeout(1500);
  await page.click('.ie-apply'); await page.waitForTimeout(2500);
  await page.goto(APP + '/library', { waitUntil: 'networkidle' }); await page.waitForTimeout(800);
  await page.fill('input[aria-label="New view name"]', 'Mine'); await page.click('button:has-text("Create")'); await page.waitForTimeout(300);
  await page.fill('input[aria-label="Search words"]', 'a'); await page.waitForTimeout(300);
  const boxes = await page.$$('.lib-results input[type=checkbox]');
  for (let i = 0; i < 6; i++) await boxes[i].check();
  await page.click('button:has-text("selected")'); await page.waitForTimeout(400);
  await page.goto(APP + '/live', { waitUntil: 'networkidle' }); await page.waitForTimeout(800);
  await page.click('button:has-text("New challenge"), button:has-text("Create a challenge"), .lv-btn.gold'); await page.waitForTimeout(500);
  const sel = page.locator('.lv-form select').first();
  const opts = await sel.locator('option').allInnerTexts();
  console.log('options tail:', opts.slice(-2));
  ok(opts.includes('Mine'), 'My views are offered');
  await sel.selectOption({ label: 'Mine' }); await page.waitForTimeout(500);
  ok((await page.innerText('.lv-summary')).startsWith('6 words'), 'the summary counts the view: ' + (await page.innerText('.lv-summary')));
  await page.click('.lv-chips button:has-text("Grammar")').catch(() => {});
  await page.screenshot({ path: `${SP}/shot-live-view.png`, fullPage: true });
  await page.click('button:has-text("Create and get the link")'); await page.waitForTimeout(1500);
  const err = await page.$('.lv-error');
  ok(!err, 'the challenge is created' + (err ? ': ' + await err.innerText() : ''));
  ok(/\/live\/[A-Z0-9]+/.test(page.url()), 'it opens the challenge room ' + page.url());
  ok(errors.length === 0, 'no page errors ' + errors.join(' / '));
  await browser.close();
});
