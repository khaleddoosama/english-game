const { APP, ok, launch, run, SP, BACKUP } = require('../helpers.cjs');
run(async () => {
  const browser = await launch();
  const page = await (await browser.newContext({ viewport: { width: 700, height: 1000 }, serviceWorkers: 'block' })).newPage();
  const errors = []; page.on('pageerror', (e) => errors.push(e.message));
  await page.goto(APP, { waitUntil: 'networkidle' });
  await page.click('text=Open Import & Export');
  await page.setInputFiles('#ie-file', BACKUP); await page.waitForTimeout(1500);
  await page.click('.ie-apply'); await page.waitForTimeout(2500);
  await page.goto(APP + '/library?new=1', { waitUntil: 'networkidle' }); await page.waitForTimeout(600);
  await page.fill('input[aria-label="New view name"]', 'Gateway'); await page.click('button:has-text("Create")'); await page.waitForTimeout(500);
  await page.goto(APP, { waitUntil: 'networkidle' }); await page.click('.wh-level-view-toggle button:has-text("Gateway")'); await page.waitForTimeout(600);
  await page.click('button[aria-label="New view inside Gateway"]'); await page.waitForTimeout(600);
  ok((await page.innerText('.lib-make')).includes('New view inside Gateway'), 'the + opens the form for a view inside Gateway');
  await page.fill('input[aria-label="New view name"]', 'A1.1'); await page.click('button:has-text("Create")'); await page.waitForTimeout(500);
  await page.goto(APP, { waitUntil: 'networkidle' }); await page.click('.wh-level-view-toggle button:has-text("Gateway")'); await page.waitForTimeout(600);
  await page.click('button[aria-label="New view inside A1.1"]'); await page.waitForTimeout(600);
  await page.fill('input[aria-label="New view name"]', 'Articles'); await page.click('button:has-text("Create")'); await page.waitForTimeout(500);
  await page.goto(APP, { waitUntil: 'networkidle' }); await page.click('.wh-level-view-toggle button:has-text("Gateway")'); await page.waitForTimeout(800);
  const tabs = await page.locator('.wh-level-view-toggle button').allInnerTexts();
  ok(JSON.stringify(tabs) === JSON.stringify(['By lesson', 'Gateway', '+', 'Catalog']), 'tabs: ' + tabs);
  const heads = await page.$$eval('.lib-readonly h3', (h) => h.map((x) => x.textContent.trim().split(' ')[0]));
  ok(JSON.stringify(heads) === JSON.stringify(['A1.1']), 'headings: ' + heads);
  const titles = await page.$$eval('.lib-readonly .wh-level-title', (h) => h.map((x) => x.textContent));
  ok(JSON.stringify(titles) === JSON.stringify(['All of Gateway', 'All of A1.1', 'Articles']), 'cards: ' + titles);
  await page.screenshot({ path: `${SP}/shot-home-nested.png` });
  ok(errors.length === 0, 'no page errors ' + errors);
  await browser.close();
});
