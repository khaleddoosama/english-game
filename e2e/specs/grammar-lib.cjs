const { APP, ok, launch, run, SP, BACKUP } = require('../helpers.cjs');
run(async () => {
  const browser = await launch();
  const page = await (await browser.newContext({ viewport: { width: 430, height: 1100 }, serviceWorkers: 'block' })).newPage();
  const errors = []; page.on('pageerror', (e) => errors.push(e.message));
  await page.goto(APP, { waitUntil: 'networkidle' });
  await page.click('text=Open Import & Export');
  await page.setInputFiles('#ie-file', BACKUP); await page.waitForTimeout(1500);
  await page.click('.ie-apply'); await page.waitForTimeout(2500);
  await page.goto(APP + '/library?new=1', { waitUntil: 'networkidle' }); await page.waitForTimeout(600);
  await page.fill('input[aria-label="New view name"]', 'Gram'); await page.click('button:has-text("Create")'); await page.waitForTimeout(600);
  ok(await page.isVisible('.lib-panel'), 'the new view opens');
  await page.click('.lib-add-rules summary'); await page.waitForTimeout(300);
  const first = page.locator('.lib-add-rules .lib-results li').first();
  const name = await first.locator('b').innerText();
  await first.locator('input').check();
  await page.click('.lib-add-rules button:has-text("Add 1 rule")'); await page.waitForTimeout(600);
  ok((await page.locator('.lib-chips li.rule span').allInnerTexts()).includes(name), 'the rule is in the view: ' + name);
  await page.screenshot({ path: `${SP}/shot-grammar-view.png`, fullPage: true });
  await page.click(`button[aria-label="Take ${name} out"]`); await page.waitForTimeout(500);
  ok((await page.locator('.lib-chips li.rule').count()) === 0, 'the x takes it out of the view');
  await page.click('[role=tab]:has-text("Library")'); await page.waitForTimeout(500);
  ok(await page.isVisible('.lib-rules'), 'the Library tab lists grammar rules (it stayed in the library)');
  await page.locator('.lib-rules .lib-results li').first().locator('input').check();
  await page.click('.lib-rules button:has-text("Remove from library")');
  await page.click('.lib-rules button:has-text("Tap again")'); await page.waitForTimeout(600);
  ok(!(await page.isVisible('.lib-rules')) || (await page.locator('.lib-rules .lib-results li').count()) === 0, 'removed from the library after the second tap');
  await page.screenshot({ path: `${SP}/shot-grammar-lib.png`, fullPage: true });
  ok(errors.length === 0, 'no page errors ' + errors);
  await browser.close();
});
